"""Builds the Classified skin: SVG sheets, skin.toml and a .psz archive.

    python3 -I -B tools/gen_classified_skin.py OUT_DIR [--ref SKIN.wsz] [--psz FILE]

Without --ref the colours fitted earlier (tools/fits.json) are used, so the
reference skin is not needed for a build.
"""
import argparse
import os
import sys
import zipfile

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

import art_eq  # noqa: E402
import art_main  # noqa: E402
import art_pl  # noqa: E402
import art_sliders  # noqa: E402
import art_title  # noqa: E402
from svgkit import Fits, Sheet  # noqa: E402

TOOLS = os.path.dirname(os.path.abspath(__file__))

# sheet name: (width, height, drawing function)
SHEETS = {
    "main": (275, 116, art_main.main),
    "cbuttons": (136, 36, art_main.cbuttons),
    "titlebar": (344, 87, art_title.titlebar),
    "shufrep": (92, 85, art_main.shufrep),
    "volume": (68, 433, art_sliders.volume),
    "balance": (68, 433, art_sliders.balance),
    "posbar": (307, 10, art_sliders.posbar),
    "text": (155, 18, art_sliders.exact),
    "numbers": (99, 13, art_sliders.exact),
    "nums_ex": (108, 13, art_sliders.exact),
    "monoster": (58, 24, art_sliders.exact),
    "playpaus": (42, 9, art_sliders.exact),
    "eqmain": (275, 315, art_eq.eqmain),
    "eq_ex": (275, 82, art_eq.eq_ex),
    "pledit": (280, 186, art_pl.pledit),
}

META = """\
# Classified: grey metal and cream buttons, after a classic 2004 skin.
# Generated by tools/gen_classified_skin.py; change the script, not this file.

[meta]
name = "Popamp Classified"
author = "Steve Gedikian, John Slegers, PeterPan, Wildrose-Wally (vector port by Popamp)"
format_version = 1
"""


# The reference's pledit.txt and viscolor.txt
PLAYLIST = """\
[playlist]
normal = "#c4ffc4"
current = "#ffffff"
normal_bg = "#000000"
selected_bg = "#6b6b6f"
"""

# Background, background dots, 16 spectrum colours from the top of a bar down, 5 oscilloscope colours, the peak dots.
VIS = [
    "#000000", "#000000", "#ef3110", "#ce2910", "#d65a00", "#d66600", "#d67300", "#c67b08",
    "#dea518", "#d6b521", "#bdde29", "#94de21", "#29ce10", "#32be10", "#39b510", "#319c08",
    "#299400", "#188408", "#ffffff", "#d6d6de", "#b5bdbd", "#a0aaaf", "#949ca5", "#969696",
]


def skin_toml():
    lines = [META, "[sheets]"]
    lines += [f'{name} = "sheets/{name}.svg"' for name in SHEETS]
    lines += ["", PLAYLIST, "[vis]", "colors = ["]
    lines += ["    " + ", ".join(f'"{c}"' for c in VIS[i : i + 8]) + "," for i in range(0, 24, 8)]
    lines += ["]"]
    return "\n".join(lines) + "\n"


def build(out, ref):
    fits = Fits(os.path.join(TOOLS, "fits.json"), ref)
    for name, (w, h, draw) in SHEETS.items():
        s = Sheet(fits, name, w, h)
        draw(s)
        s.save(os.path.join(out, "sheets", f"{name}.svg"))
    with open(os.path.join(out, "skin.toml"), "w") as f:
        f.write(skin_toml())
    fits.save()


def pack(out, psz):
    with zipfile.ZipFile(psz, "w", zipfile.ZIP_DEFLATED) as z:
        z.write(os.path.join(out, "skin.toml"), "skin.toml")
        for name in sorted(os.listdir(os.path.join(out, "sheets"))):
            z.write(os.path.join(out, "sheets", name), f"sheets/{name}")


def main():
    p = argparse.ArgumentParser()
    p.add_argument("out")
    p.add_argument("--ref", help="the reference skin (.wsz or folder) to fit colours on")
    p.add_argument("--psz", help="also write this .psz archive")
    a = p.parse_args()
    build(a.out, a.ref)
    if a.psz:
        pack(a.out, a.psz)


if __name__ == "__main__":
    main()
